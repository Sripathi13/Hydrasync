export function generateInitialHistory(points: number = 30): TelemetryReading[] {
  const readings: TelemetryReading[] = [];
  const now = Date.now();
  const stepMs = 60 * 1000; // 1 minute per point

  for (let i = points - 1; i >= 0; i--) {
    const time = new Date(now - i * stepMs);
    // Base diurnal fluctuation
    const hourAngle = (time.getHours() * 60 + time.getMinutes()) / 720 * Math.PI;
    const diurnal = Math.sin(hourAngle) * 20;

    const expectedFlow = 510 + diurnal;
    // Section B has had a small leak in recent minutes
    const leakFactor = i < 15 ? 24 : 12;
    const actualFlow = expectedFlow + leakFactor + (Math.random() * 6 - 3);

    readings.push({
      timestamp: time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      flow: Number(actualFlow.toFixed(1)),
      expectedFlow: Number(expectedFlow.toFixed(1)),
      flowDeviation: Number((actualFlow - expectedFlow).toFixed(1)),
      pressureA: Number((5.2 + (Math.random() * 0.1 - 0.05)).toFixed(2)),
      pressureB: Number((3.9 + (Math.random() * 0.15 - 0.07)).toFixed(2)),
      pressureC: Number((4.6 + (Math.random() * 0.08 - 0.04)).toFixed(2)),
      pressureD: Number((4.1 + (Math.random() * 0.08 - 0.04)).toFixed(2)),
      pumpPressure: Number((6.4 + (Math.random() * 0.1 - 0.05)).toFixed(2)),
      reservoirLevel: Number((84.5 - (points - i) * 0.03).toFixed(1)),
      temperature: Number((19.4 + Math.sin(i / 5) * 0.4).toFixed(1)),
      productionDemand: Number((82 + Math.cos(i / 6) * 6).toFixed(1)),
      solarKW: Number((140 + Math.max(0, Math.sin(hourAngle) * 90)).toFixed(1)),
      gridKW: Number((310 - Math.max(0, Math.sin(hourAngle) * 40)).toFixed(1)),
      batteryKW: 45.0,
      anomalyScore: i < 15 ? 68 : 42,
      leakRate: i < 15 ? 3.8 : 2.1,
      systemHealth: i < 15 ? 'WARNING' : 'NORMAL',
    });
  }

  return readings;
}
